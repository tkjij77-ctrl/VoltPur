package org.purpurmc.purpur;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

public class VoltPurTuningTest {

    private Path tempWorkDir;

    @BeforeEach
    void setUp() throws IOException {
        tempWorkDir = Files.createTempDirectory("voltpur-tuning-test");
    }

    @AfterEach
    void tearDown() throws IOException {
        VoltPurConfig.hardwareAutoTune = false;
        if (Files.exists(tempWorkDir)) {
            try (var stream = Files.walk(tempWorkDir)) {
                stream.sorted((a, b) -> b.compareTo(a))
                        .forEach(p -> {
                            try { Files.deleteIfExists(p); } catch (Exception ignored) {}
                        });
            }
        }
    }

    @Test
    void testApplyOptimizationsUpdatesSpigotYmlWithMergeRadius() throws IOException {
        Path spigotYml = tempWorkDir.resolve("spigot.yml");
        List<String> lines = List.of(
                "# Spigot Configuration file",
                "# Do not remove this comment!",
                "",
                "world-settings:",
                "  default:",
                "    verbose: false",
                "    merge-radius:",
                "      item: 2.5",
                "      exp: 3.0",
                "    ticks-per:",
                "      hopper-check: 1",
                "      hopper-transfer: 8"
        );
        Files.write(spigotYml, lines, StandardCharsets.UTF_8);

        VoltPurConfig.hardwareAutoTune = true;
        boolean applied = VoltPurTuning.applyOptimizations(spigotYml);
        assertTrue(applied);

        assertTrue(Files.exists(spigotYml));
        List<String> updated = Files.readAllLines(spigotYml, StandardCharsets.UTF_8);

        // Verify comments preserved 100%
        assertTrue(updated.contains("# Spigot Configuration file"));
        assertTrue(updated.contains("# Do not remove this comment!"));

        // Verify merge-radius (§4.3 Priority 2: item: 4.0, exp: 6.0)
        assertTrue(updated.stream().anyMatch(l -> l.contains("item: 4.0")), "merge-radius.item should be 4.0");
        assertTrue(updated.stream().anyMatch(l -> l.contains("exp: 6.0")), "merge-radius.exp should be 6.0");

        // Verify hopper-check tuned
        assertTrue(updated.stream().anyMatch(l -> l.contains("hopper-check: 8")), "hopper-check should be 8");

        // Verify backup created
        Path bak = tempWorkDir.resolve("spigot.yml.bak");
        assertTrue(Files.exists(bak), "spigot.yml.bak must be created");
    }

    @Test
    void testApplyServerPropertiesPreservesComments() throws IOException {
        Path serverProps = tempWorkDir.resolve("server.properties");
        List<String> lines = List.of(
                "# Minecraft server properties",
                "# Generated by server installer",
                "view-distance=10",
                "simulation-distance=10",
                "network-compression-threshold=256"
        );
        Files.write(serverProps, lines, StandardCharsets.UTF_8);

        VoltPurConfig.hardwareAutoTune = true;
        boolean applied = VoltPurTuning.applyServerProperties(serverProps);
        assertTrue(applied);

        assertTrue(Files.exists(serverProps));
        List<String> updated = Files.readAllLines(serverProps, StandardCharsets.UTF_8);

        // Verify comments preserved
        assertTrue(updated.contains("# Minecraft server properties"));
        assertTrue(updated.contains("# Generated by server installer"));

        // Verify backup created
        Path bak = tempWorkDir.resolve("server.properties.bak");
        assertTrue(Files.exists(bak), "server.properties.bak must be created");
    }

    @Test
    void testWriteTuningSheetGeneratesFile() throws IOException {
        Path sheet = tempWorkDir.resolve("logs/voltpur-tuning.txt");
        VoltPurTuning.writeTuningSheet(sheet);
        assertTrue(Files.exists(sheet));
        String content = Files.readString(sheet);
        assertTrue(content.contains("=== VoltPur Hardware Tuning Sheet ==="));
        assertTrue(content.contains("view-distance="));
    }
}
